ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS prescription_review_status VARCHAR(30);

CREATE TABLE IF NOT EXISTS public.order_prescription_reviews (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL UNIQUE REFERENCES public.orders(id) ON DELETE CASCADE,
    prescription_id INTEGER NOT NULL REFERENCES public.prescriptions(id) ON DELETE RESTRICT,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING_APPROVAL'
        CHECK (status IN ('PENDING_APPROVAL', 'APPROVED', 'REJECTED')),
    pharmacist_id INTEGER REFERENCES public.employees(id) ON DELETE SET NULL,
    facility_id INTEGER NOT NULL REFERENCES public.facilities(id) ON DELETE RESTRICT,
    note TEXT,
    reviewed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_order_prescription_reviews_queue
    ON public.order_prescription_reviews (facility_id, status, created_at);
CREATE INDEX IF NOT EXISTS idx_order_prescription_reviews_prescription
    ON public.order_prescription_reviews (prescription_id);
